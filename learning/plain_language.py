    assert set(LESSON_COPY)==set(METHODS)==set(CHECK_COPY)==set(lessons)
    for key,new in LESSON_COPY.items():
        lessons[key]['principle']=new['principle']
        lessons[key]['sections']=list(new['sections'])
        lessons[key]['case']=tuple(simple(p) for p in lessons[key]['case'])
        lessons[key]['checks']=list(CHECK_COPY[key])
    additions={
        'control':'可以先挑一种最常见的错误，观察一次真实操作，再决定如何改善。',
        'launch':'每个缺口都安排一个具体负责人。',
    }
    for key,addition in additions.items():
        heading,body=lessons[key]['sections'][0]
        lessons[key]['sections'][0]=(heading,body+addition)
    for t in topics:
        key=t['id'];p=plans[key]
        p['method']=METHODS[key]
        p['output']=OUTPUTS[key]
        p['steps']=[heading for heading,_ in LESSON_COPY[key]['sections']]
        p['task']=simple(p['task'])
        p['answer']=PRACTICE_ANSWERS.get(key,simple(p['answer'])) if key!='tco' else simple(p['answer'])
        t['cards']=[lessons[key]['principle'],simple(t['cards'][1]),simple(t['cards'][2])]
        for field in ('scenario','quiz'):
            q=t[field]
            for k,v in q.items():
                if isinstance(v,str):q[k]=simple(v)
                elif isinstance(v,list):q[k]=[simple(x) for x in v]
        if key in QUIZ_COPY:
            prompt,answer=QUIZ_COPY[key]
            t['quiz']['prompt']=prompt
            t['quiz']['options'][t['quiz']['answer']]=answer
            t['quiz']['feedback']=QUIZ_FEEDBACK[key]
        t['title']=simple(t['title'])

