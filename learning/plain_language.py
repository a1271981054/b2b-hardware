from html.parser import HTMLParser
from html import escape
_PATTERN = re.compile('|'.join(re.escape(k) for k in sorted(GLOSS,key=len,reverse=True)))
class HelpfulHTML(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.parts=[];self.stack=[];self.seen=set();self.inline_count=0
    def handle_starttag(self,tag,attrs):
        self.parts.append(self.get_starttag_text())
        if tag not in ('br','img','hr','input','meta','link','wbr','source'):
            self.stack.append(tag)
    def handle_startendtag(self,tag,attrs): self.parts.append(self.get_starttag_text())
    def handle_endtag(self,tag):
        self.parts.append('</'+tag+'>')
        if tag in self.stack:
            self.stack=self.stack[:len(self.stack)-1-self.stack[::-1].index(tag)]
    def handle_entityref(self,name): self.parts.append('&'+name+';')
    def handle_charref(self,name): self.parts.append('&#'+name+';')
    def handle_data(self,data):
        if any(t in self.stack for t in ('a','button','code','pre','script','style','h1','h2','h3','h4','h5','h6')):
            self.parts.append(data);return
        def replace(match):
            term=match.group()
            # Do not explain PM inside RPM, MP inside another acronym, etc.
            if re.fullmatch(r'[A-Za-z]+',term):
                a,b=match.span()
                if (a and re.match(r'[A-Za-z]',data[a-1])) or (b<len(data) and re.match(r'[A-Za-z]',data[b])):return term
            first=term not in self.seen;self.seen.add(term)
            button='<button type="button" class="word-help" data-action="explain-term" data-term="'+escape(term,quote=True)+'" aria-label="解释：'+escape(term,quote=True)+'">'+escape(term)+'</button>'
            # Tables keep their width. Their terms remain available by tap.
            # Avoid automatic notes for already explained terms in authored text.
            if first and not any(t in self.stack for t in ('td','th')) and self.inline_count<3 and term in ('口径','边界','闭环','放行','矩阵','基线','幂等','灰度','归一化','时间窗'):
                self.inline_count+=1
                button+='<span class="word-inline">（'+escape(GLOSS[term])+'）</span>'
            return button
        self.parts.append(_PATTERN.sub(replace,data))

def help_html(html):
    parser=HelpfulHTML();parser.feed(html);parser.close();return ''.join(parser.parts)

def simple_markdown(text):
    # Keep fenced code and inline code literal, including formulas and examples.
    chunks=re.split(r'(```[\s\S]*?```|`[^`\n]+`)',text)
    return ''.join(chunk if i%2 else simple(chunk) for i,chunk in enumerate(chunks))


